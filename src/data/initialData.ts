function generateSampleTasks(
  weekId: string,
  startStr: string,
  total: number,
  completedCount: number,
  _targetRatio: number
): Task[] {
  const subjects = ['Java OOP', 'Data Structures', 'Web Development', 'SQL & Databases', 'System Design', 'Project Work', 'Weekly Review'];
  const days: DayOfWeek[] = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
  const priorities: Array<'High' | 'Medium' | 'Low'> = ['High', 'High', 'Medium', 'Medium', 'Low'];
  
  const tasks: Task[] = [];
  let completedLeft = completedCount;

  for (let i = 0; i < total; i++) {
    const dayIdx = i % 7;
    const day = days[dayIdx];
    const subject = subjects[dayIdx];
    const priority = priorities[i % priorities.length];
    const isComp = completedLeft > 0 && (i < completedCount || Math.random() > 0.3);
    if (isComp) completedLeft--;

    tasks.push({
      id: `${weekId}-t-${i + 1}`,
      weekId,
      date: startStr,
      day,
      subject,
      goal: `Advance in ${subject} key deliverables`,
      taskName: `Module ${i + 1}: ${subject} practical exercises & review`,
      priority,
      status: isComp ? 'completed' : 'pending',
      createdDate: `${startStr}T08:00:00.000Z`,
      completedDate: isComp ? `${startStr}T17:00:00.000Z` : null,
      notes: isComp ? 'Completed on schedule' : undefined,
    });
  }

  return tasks;
}
